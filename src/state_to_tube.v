module state_to_tube(
    input [4:0] state,
    output [15:0] tube_content
    );

    assign tube_content =
        (state == 5'b00000) ? 16'b1111_1100_1111_1101 :   //"00." 
        (state == 5'b00001) ? 16'b1111_1100_0110_0001 :   //"01." 
        (state == 5'b00010) ? 16'b1111_1100_1101_1011 :   //"02." 
        (state == 5'b00011) ? 16'b1111_1100_1111_0011 :   //"03."
        (state == 5'b00100) ? 16'b1111_1100_0110_0111 :   //"04."
        (state == 5'b00101) ? 16'b1111_1100_1011_0111 :   //"05."
        (state == 5'b00110) ? 16'b1111_1100_1011_1111 :   //"06."
        (state == 5'b00111) ? 16'b1111_1100_1110_0001 :   //"07."
        (state == 5'b01000) ? 16'b1111_1100_1111_1111 :   //"08."
        (state == 5'b01001) ? 16'b1111_1100_1110_0111 :   //"09."
        
        (state == 5'b01010) ? 16'b0110_0000_1111_1101 :   //"10." 
        (state == 5'b01011) ? 16'b0110_0000_0110_0001 :   //"11." 
        (state == 5'b01100) ? 16'b0110_0000_1101_1011 :   //"12." 
        (state == 5'b01101) ? 16'b0110_0000_1111_0011 :   //"13."
        (state == 5'b01110) ? 16'b0110_0000_0110_0111 :   //"14."
        (state == 5'b01111) ? 16'b0110_0000_1011_0111 :   //"15."
        (state == 5'b10000) ? 16'b0110_0000_1011_1111 :   //"16."
        (state == 5'b10001) ? 16'b0110_0000_1110_0001 :   //"17."
        (state == 5'b10010) ? 16'b0110_0000_1111_1111 :   //"18."
        (state == 5'b10011) ? 16'b0110_0000_1110_0111 :   //"19."
        16'b1001_1110_1001_1111;                       //"EE."

endmodule
